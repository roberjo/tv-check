"""Check that every function call resolves in its own component's scope.

On the TV, each SceneGraph component sees only the functions in the scripts
its XML lists (and the main thread sees only source/). The off-device tests
load every .brs file together, so a scene function that calls something
defined only in DataTask's scope passes the tests but fails on the TV, as
`isText` did in 1.13.0.

For each scope this reads the <script uri> list (or every file under source/
for the main thread), collects the functions and subs it defines, and reports
every call to a name with no definition there, by file and line. Method calls
(`.name(`), BrightScript built-ins and the language's keywords are excluded.

Usage:  python3 daybreak/check_scope.py [channel_dir]
Exits 1 if any call is unresolved. Stdlib only.
"""
import pathlib
import re
import sys
import xml.etree.ElementTree as ET

# Global functions of the BrightScript runtime (ifGlobal and the language).
BUILTINS = {
    # utility
    "createobject", "getinterface", "type", "box", "run", "eval", "getlastruncompileerror", "getlastrunruntimeerror",
    "sleep", "wait", "uptime", "rebootsystem", "listdir", "readasciifile", "writeasciifile", "copyfile", "movefile",
    "matchfiles", "deletefile", "deletedirectory", "createdirectory", "formatdrive", "strtoi", "getglobalaa",
    "parsejson", "formatjson", "tr", "objfun", "createobjectwithiface",
    # string
    "ucase", "lcase", "asc", "chr", "instr", "left", "len", "mid", "right", "str", "stri", "string", "stringi",
    "val", "substitute", "strtrim",
    # math
    "abs", "atn", "cdbl", "cint", "cos", "csng", "exp", "fix", "int", "log", "rnd", "sgn", "sin", "sqr", "tan",
    # SceneGraph threads
    "createchild", "getchild",
}
# Statements and operators that are followed by "(" in ordinary code.
KEYWORDS = {
    "if", "elseif", "else", "while", "for", "to", "step", "each", "in", "return", "print", "and", "or", "not",
    "mod", "function", "sub", "then", "end", "exit", "goto", "dim", "stop", "throw", "try", "catch", "as",
    "invalid", "true", "false", "m", "line_num",
}
DEF_RE = re.compile(r"^\s*(?:function|sub)\s+([A-Za-z_][A-Za-z0-9_]*)\s*\(", re.I)
CALL_RE = re.compile(r"(?<![.\w@])([A-Za-z_][A-Za-z0-9_]*)\s*\(")
LOCAL_RE = re.compile(r"^\s*([A-Za-z_][A-Za-z0-9_]*)\s*=\s*(?:function|sub)\s*\(", re.I)


def strip_line(line):
    """The line without string literals and its trailing comment."""
    out, in_str = [], False
    i = 0
    while i < len(line):
        c = line[i]
        if in_str:
            if c == '"':
                if i + 1 < len(line) and line[i + 1] == '"':
                    i += 2
                    continue
                in_str = False
            out.append(" ")
        elif c == '"':
            in_str = True
            out.append(" ")
        elif c == "'":
            break
        else:
            out.append(c)
        i += 1
    code = "".join(out)
    if re.match(r"^\s*rem(\s|$)", code, re.I):
        return ""
    return code


def defined_in(path):
    return {m.group(1).lower() for line in path.read_text().splitlines() if (m := DEF_RE.match(line))}


def calls_in(path):
    for n, line in enumerate(path.read_text().splitlines(), 1):
        code = strip_line(line)
        if DEF_RE.match(code):
            code = code[code.index("(") + 1:]  # the parameter list may call functions for defaults
        for m in CALL_RE.finditer(code):
            yield n, m.group(1)


def scopes(ch):
    """(scope name, [files]) for the main thread and each component."""
    src = sorted((ch / "source").rglob("*.brs"))
    yield "source/", src
    for xml in sorted((ch / "components").rglob("*.xml")):
        files = []
        for s in ET.parse(xml).getroot().iter("script"):
            uri = s.get("uri", "")
            if uri.startswith("pkg:/"):
                files.append(ch / uri[len("pkg:/"):])
        yield xml.relative_to(ch).as_posix(), files


def check(ch):
    problems = []
    for name, files in scopes(ch):
        missing = [f for f in files if not f.exists()]
        for f in missing:
            # source/config.brs is generated by build_channel.py; only a real gap if it's never built
            problems.append(f"{name}: script not found: {f.relative_to(ch)}")
        files = [f for f in files if f.exists()]
        known = set().union(*(defined_in(f) for f in files)) if files else set()
        for f in files:
            local = {m.group(1).lower() for line in f.read_text().splitlines() if (m := LOCAL_RE.match(line))}
            for n, called in calls_in(f):
                low = called.lower()
                if low in known or low in BUILTINS or low in KEYWORDS or low in local:
                    continue
                problems.append(f"{f.relative_to(ch)}:{n}: {called}() is not defined in the {name} scope")
    return problems


if __name__ == "__main__":
    ch = pathlib.Path(sys.argv[1]) if len(sys.argv) > 1 else pathlib.Path(__file__).resolve().parent / "channel"
    problems = check(ch)
    for p in problems:
        print(p)
    print(f"scope check: {len(problems)} unresolved call(s)")
    sys.exit(1 if problems else 0)
