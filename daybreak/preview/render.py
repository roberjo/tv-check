"""Draw Daybreak scene dumps (from preview.brs) the way the TV would.

Reads the SCENE lines printed by preview.brs, draws each node tree with the
package's own fonts and 9-patch images (daybreak/channel/fonts and images,
generated by build_channel.py), and writes one PNG per screen.

--audit also checks every label: text below 24 px, and WCAG contrast against
the brightest 2% of what's drawn behind it (4.5:1, or 3:1 for large text).
--docs writes 1280x720 JPEGs for docs/images, without team logos: they're the
teams' trademarks, so they stay out of this repo (the TV loads them from ESPN).
--stable draws only what's in the repo: no team logos (as --docs) and no
radar base map (fetched from a tile server), for visual_diff.py.
--wallpaper-report <file> audits the wallpapers.brs dump: it writes each
photo's issue count per screen as JSON and 960x540 JPEGs to look over.

Usage: render.py <dump.txt> <out-dir> [--audit] [--docs <dir>] [--stable] [--wallpaper-report <file>]
"""
import json
import pathlib
import re
import sys
import urllib.request

from PIL import Image, ImageDraw, ImageFont

HERE = pathlib.Path(__file__).resolve().parent
CH = HERE.parent / "channel"
WALL = HERE.parent / "wallpapers" / "img"  # cachefs:/wp-<id>.jpg on the TV
LOGOS = HERE.parent / "cache" / "logos"  # team logos, downloaded like the TV does (gitignored)
W, H = 1920, 1080
DOCS = {("morning", "briefing"): "briefing", ("morning", "ambient"): "ambient", ("morning", "recap"): "recap",
        ("morning", "gameday"): "gameday", ("evening", "week"): "week", ("evening", "sky"): "sky",
        ("evening", "tonight"): "tonight", ("morning", "lake"): "lake", ("morning", "weekend"): "weekend", ("warning", "radar"): "radar"}
_fonts = {}
_images = {}


def rgba(v, opacity=1.0):
    """'0xRRGGBBAA' or an integer -> (r, g, b, a) with opacity applied."""
    if isinstance(v, str):
        v = int(v, 16)
    v = int(v) & 0xFFFFFFFF
    return (v >> 24 & 255, v >> 16 & 255, v >> 8 & 255, round((v & 255) * opacity))


def font(uri, size):
    key = (uri, size)
    if key not in _fonts:
        # BASIC layout everywhere: Pillow's Linux wheels shape text with libraqm and
        # macOS installs often lack it, which moves glyph edges (visual_diff.py)
        _fonts[key] = ImageFont.truetype(str(CH / uri.replace("pkg:/", "")), size, layout_engine=ImageFont.Layout.BASIC)
    return _fonts[key]


def logo(uri):
    """A team logo from ESPN's CDN (the TV loads them live), cached in daybreak/cache/logos; None offline."""
    path = LOGOS / uri.split("/teamlogos/", 1)[1].replace("/", "_")
    if not path.exists():
        try:
            with urllib.request.urlopen(uri, timeout=20) as r:
                LOGOS.mkdir(parents=True, exist_ok=True)
                path.write_bytes(r.read())
        except OSError:
            return None
    return Image.open(path).convert("RGBA")


def image(uri):
    if uri.startswith("https://a.espncdn.com/i/teamlogos/"):
        if "--docs" in sys.argv or "--stable" in sys.argv:
            return None
        if uri not in _images:
            _images[uri] = logo(uri)
        return _images[uri]
    if uri == "pkg:/images/radar_base.jpg" and "--stable" in sys.argv:
        return None
    if uri not in _images:
        path = CH / uri.replace("pkg:/", "")
        if uri.startswith("cachefs:/wp-"):
            path = WALL / uri[len("cachefs:/wp-"):]
        ok = uri.startswith(("pkg:/", "cachefs:/wp-")) and path.exists()
        _images[uri] = Image.open(path).convert("RGBA") if ok else None
    return _images[uri]


def nine_slice(src, w, h):
    """Roku 9-patch: 1px marker border; the corner size is where the top marker starts."""
    inner = src.crop((1, 1, src.width - 1, src.height - 1))
    top = [x for x in range(src.width) if src.getpixel((x, 0))[3] > 0]
    r = (top[0] - 1) if top else inner.width // 2
    w, h = max(int(w), 1), max(int(h), 1)
    r = min(r, w // 2, h // 2)
    out = Image.new("RGBA", (w, h))
    iw, ih = inner.size
    cols = [(0, r, 0, r), (r, iw - r, r, w - r), (iw - r, iw, w - r, w)]
    rows = [(0, r, 0, r), (r, ih - r, r, h - r), (ih - r, ih, h - r, h)]
    for sx0, sx1, dx0, dx1 in cols:
        for sy0, sy1, dy0, dy1 in rows:
            if sx1 > sx0 and sy1 > sy0 and dx1 > dx0 and dy1 > dy0:
                out.paste(inner.crop((sx0, sy0, sx1, sy1)).resize((dx1 - dx0, dy1 - dy0)), (dx0, dy0))
    return out


def tint(im, blend, opacity):
    r, g, b, a = rgba(blend, opacity) if blend is not None else (255, 255, 255, round(255 * opacity))
    ch = im.split()
    out = [c.point(lambda p, k=k: p * k // 255) for c, k in zip(ch[:3], (r, g, b))]
    out.append(ch[3].point(lambda p: p * a // 255))
    return Image.merge("RGBA", out)


def wrap_lines(text, f, width, wrap, max_lines):
    if not wrap or width <= 0:
        lines = [text]
    else:
        lines, cur = [], ""
        for word in text.split(" "):
            trial = (cur + " " + word).strip()
            if cur and f.getlength(trial) > width:
                lines.append(cur)
                cur = word
            else:
                cur = trial
        lines.append(cur)
    if max_lines and len(lines) > max_lines:
        lines = lines[:max_lines]
        lines[-1] += " " + "…"
    if width > 0:
        lines = [ellipsize(l, f, width) for l in lines]
    return lines


def ellipsize(line, f, width):
    if f.getlength(line) <= width:
        return line
    while line and f.getlength(line + "...") > width:
        line = line[:-1]
    return line.rstrip() + "..."


class Renderer:
    def __init__(self, with_labels=True):
        self.canvas = Image.new("RGBA", (W, H), (0, 0, 0, 255))
        self.with_labels = with_labels
        self.labels = []

    def draw(self, node, ox=0.0, oy=0.0, opacity=1.0):
        if node.get("visible") is False:
            return
        x, y = ox + node.get("x", 0), oy + node.get("y", 0)
        op = opacity * node.get("opacity", 1.0)
        t = node["t"]
        if t == "Rectangle" and node.get("width") and node.get("height"):
            layer = Image.new("RGBA", (int(node["width"]), int(node["height"])), rgba(node.get("color", "0xFFFFFFFF"), op))
            self.canvas.alpha_composite(layer, (int(x), int(y)))
        elif t == "Poster" and node.get("uri"):
            src = image(node["uri"])
            w, h = node.get("width") or 0, node.get("height") or 0
            if src is not None and w > 0 and h > 0:
                im = nine_slice(src, w, h) if node["uri"].endswith(".9.png") else src.resize((int(w), int(h)))
                self.paste(tint(im, node.get("blendColor"), op), x, y)
        elif t == "Label" and node.get("text"):
            self.label(node, x, y, op)
        for kid in node.get("kids", []):
            self.draw(kid, x, y, op)

    def paste(self, im, x, y):
        x, y = int(round(x)), int(round(y))
        if x >= W or y >= H or x + im.width <= 0 or y + im.height <= 0:
            return
        layer = Image.new("RGBA", (W, H))
        layer.paste(im, (x, y))
        self.canvas.alpha_composite(layer)

    def label(self, node, x, y, op):
        size = int(node.get("size", 22))
        f = font(node.get("font", "pkg:/fonts/Manrope-400.ttf"), size)
        width = node.get("width") or 0
        lines = wrap_lines(node["text"], f, width, node.get("wrap", False), node.get("maxLines", 0))
        ascent, descent = f.getmetrics()
        step = ascent + descent + (node.get("lineSpacing", 0) if node.get("wrap") else 0)
        color = rgba(node.get("color", "0xFFFFFFFF"), op)
        align = node.get("horizAlign", "left")
        boxes = []
        for i, line in enumerate(lines):
            lw = f.getlength(line)
            lx = x + (width - lw if align == "right" else (width - lw) / 2 if align == "center" else 0) if width else x
            ly = y + i * step
            boxes.append((lx, ly, lx + lw, ly + ascent + descent))
            if self.with_labels:
                ImageDraw.Draw(self.canvas).text((lx, ly), line, font=f, fill=color)
        weight = int(re.search(r"-(\d+)\.ttf", node.get("font", "-400.ttf")).group(1))
        self.labels.append({"text": node["text"], "size": size, "weight": weight, "color": color, "boxes": boxes})


def lum(rgb):
    def lin(c):
        c /= 255
        return c / 12.92 if c <= 0.04045 else ((c + 0.055) / 1.055) ** 2.4
    r, g, b = (lin(v) for v in rgb[:3])
    return 0.2126 * r + 0.7152 * g + 0.0722 * b


def audit(tree):
    """Labels under 24 px, and contrast below WCAG against the brightest 2% behind each line."""
    bg = Renderer(with_labels=False)
    bg.draw(tree)
    issues = []
    for lb in bg.labels:
        if lb["size"] < 24:
            issues.append(f"small {lb['size']}px: {lb['text'][:48]!r}")
        large = lb["size"] >= 24 or (lb["size"] >= 19 and lb["weight"] >= 700)
        need = 3.0 if large else 4.5
        for (x0, y0, x1, y1) in lb["boxes"]:
            box = (max(0, int(x0)), max(0, int(y0)), min(W, int(x1)), min(H, int(y1)))
            if box[2] - box[0] < 2 or box[3] - box[1] < 2:
                continue
            px = list(bg.canvas.crop(box).convert("RGB").resize((40, 12)).get_flattened_data())
            ls = sorted(lum(p) for p in px)
            worst = ls[int(len(ls) * 0.98) - 1]
            r, g, b, a = lb["color"]
            # text alpha blends over the average background
            avg = [sum(p[i] for p in px) / len(px) for i in range(3)]
            text = [c * a / 255 + bgc * (1 - a / 255) for c, bgc in zip((r, g, b), avg)]
            ratio = (max(lum(text), worst) + 0.05) / (min(lum(text), worst) + 0.05)
            if ratio < need:
                issues.append(f"contrast {ratio:.1f}:1 < {need}: {lb['text'][:48]!r}")
                break
    return issues


def main():
    dump, out = pathlib.Path(sys.argv[1]), pathlib.Path(sys.argv[2])
    do_audit = "--audit" in sys.argv
    docs = pathlib.Path(sys.argv[sys.argv.index("--docs") + 1]) if "--docs" in sys.argv else None
    report = pathlib.Path(sys.argv[sys.argv.index("--wallpaper-report") + 1]) if "--wallpaper-report" in sys.argv else None
    do_audit = do_audit or report is not None
    results = {}
    if not (CH / "fonts").exists():
        sys.exit("Fonts and images are missing: run daybreak/build_channel.py once first.")
    out.mkdir(parents=True, exist_ok=True)
    total = 0
    for line in dump.read_text().splitlines():
        if not line.startswith("SCENE|"):
            if line.strip() and not line.startswith("LIVE SMOKE"):
                print(line)
            continue
        _, scenario, screen, payload = line.split("|", 3)
        tree = json.loads(payload.replace("{Q}", '\\"'))
        r = Renderer()
        r.draw(tree)
        img = r.canvas.convert("RGB")
        if report:
            img.resize((960, 540), Image.LANCZOS).save(out / f"{scenario[3:]}_{screen}.jpg", quality=70)
        else:
            img.save(out / f"{scenario}_{screen}.png")
        if docs and (scenario, screen) in DOCS:
            docs.mkdir(parents=True, exist_ok=True)
            img.resize((1280, 720), Image.LANCZOS).save(docs / f"{DOCS[scenario, screen]}.jpg", "JPEG", quality=85, optimize=True)
        msg = f"{scenario}/{screen}"
        if do_audit:
            issues = audit(tree)
            total += len(issues)
            if report:
                results.setdefault(scenario[3:], {})[screen] = len(issues)
            msg += f": {len(issues)} issue(s)" + "".join("\n    " + i for i in issues)
        print(msg)
    if report:
        report.parent.mkdir(parents=True, exist_ok=True)
        report.write_text(json.dumps(results, indent=1) + "\n")
        print(f"wallpaper audit: {len(results)} photos, report in {report}")
        return
    if do_audit:
        print(f"audit: {total} issue(s)")
        sys.exit(1 if total else 0)


if __name__ == "__main__":
    main()
