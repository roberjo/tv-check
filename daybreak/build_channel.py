"""Build the standalone Daybreak Roku channel.

Generates everything the app bundles (static font weights, tintable 9-patch
cards, icons, moon phases, pre-dimmed backgrounds, radar base map), writes
source/config.brs from config/family.json + .env (gitignored: it holds the
private calendar URL), validates with BrighterScript, and zips to
daybreak/dist/daybreak.zip. Installs nothing.

The package's manifest gets build_version = the git commit count, so each
install is distinguishable; the tracked manifest keeps major/minor only.

Usage:
  .venv/bin/python daybreak/build_channel.py            # full build + zip
  .venv/bin/python daybreak/build_channel.py --check    # example config + BrighterScript only (CI)
  .venv/bin/python daybreak/build_channel.py --assets   # example config + fonts + images, for previews (CI)
"""
