def brs_str(s):
    return '"' + str(s).replace('"', '""') + '"'


def brs_val(v):
    if isinstance(v, bool):
        return "true" if v else "false"
    return brs_str(v) if isinstance(v, str) else str(v)


def write_config():
    members = ", ".join(
        "{" + ", ".join(f"{k}: {brs_val(v)}" for k, v in
                        [("name", m["name"]), ("color", m["color"]), ("birthday", m["birthday"]),
                         ("allegiance", m.get("allegiance", ""))] + ([("school", m["school"]), ("grade", m["grade"])] if m.get("school") else [])
                        + ([("band", True)] if "Marching band" in m.get("activities", []) else []))
        + "}" for m in family["members"])
    (CH / "source" / "config.brs").write_text(f"""' Generated by daybreak/build_channel.py from config/family.json and .env.
' Not committed: contains the family calendar's private iCal URL.
function DaybreakConfig() as object
    return {{
        household: {brs_str(family["household"])},
        city: {brs_str(family["home"]["city"])},
        lat: {family["home"]["lat"]}, lon: {family["home"]["lon"]},
        curbWeekday: 1,
        apps: [{", ".join(brs_str(a) for a in family.get("apps", [])[:6])}],
        calendarUrl: {brs_str(env.get("FAMILY_CALENDAR_ICS", ""))},
        members: [{members}]
    }}
end function
""")


def make_fonts():
    from fontTools.ttLib import TTFont
    from fontTools.varLib import instancer
    FONTS.mkdir(exist_ok=True)
    for fam, weights in (("Outfit", (200, 300, 400, 500, 600)), ("Manrope", (400, 500, 600, 700, 800))):
        for w in weights:
            out = FONTS / f"{fam}-{w}.ttf"
            if not out.exists():
                instancer.instantiateVariableFont(TTFont(SRC_FONTS / f"{fam}.ttf"), {"wght": w}).save(out)
    for old in ("Outfit-Light.ttf", "Outfit-ExtraLight.ttf"):
        (FONTS / old).unlink(missing_ok=True)
    (FONTS / "OFL-Outfit.txt").write_text((SRC_FONTS / "OFL-Outfit.txt").read_text())
    (FONTS / "OFL-Manrope.txt").write_text((SRC_FONTS / "OFL-Manrope.txt").read_text())
    (FONTS / "OFL.txt").unlink(missing_ok=True)


def nine_patch(r, ring=False, width=2):
    """White rounded rect as a Roku 9-patch: 1px marker border, stretch at the center row/column."""
    inner = 2 * r + 1
    k = 4
    big = Image.new("RGBA", (inner * k, inner * k), (255, 255, 255, 0))
    dd = ImageDraw.Draw(big)
    if ring:
        dd.rounded_rectangle((0, 0, inner * k - 1, inner * k - 1), r * k, outline=(255, 255, 255, 255), width=width * k)
    else:
        dd.rounded_rectangle((0, 0, inner * k - 1, inner * k - 1), r * k, fill=(255, 255, 255, 255))
    small = big.resize((inner, inner), Image.LANCZOS)
    im = Image.new("RGBA", (inner + 2, inner + 2), (0, 0, 0, 0))
    im.paste(small, (1, 1))
    im.putpixel((r + 1, 0), (0, 0, 0, 255))
    im.putpixel((0, r + 1), (0, 0, 0, 255))
    return im


def icon(kind, s=128, st=9):
    im = Image.new("RGBA", (s, s), (0, 0, 0, 0))
    d = ImageDraw.Draw(im)
    W_ = (255, 255, 255, 255)
    clear = (0, 0, 0, 0)
    cx = cy = s / 2

    def sun(x, y, r):
        d.ellipse((x - r, y - r, x + r, y + r), outline=W_, width=st)
        for i in range(8):
            a = i * math.pi / 4
            d.line((x + math.cos(a) * r * 1.5, y + math.sin(a) * r * 1.5, x + math.cos(a) * r * 2.0, y + math.sin(a) * r * 2.0), fill=W_, width=st)

    def cloud(x, y, w):
        """Cloud silhouette (two puffs on a rounded base) drawn as an outline; clears what's behind it."""
        from PIL import ImageChops, ImageFilter
        k = 4
        mask = Image.new("L", (s * k, s * k), 0)
        md = ImageDraw.Draw(mask)
        X, Y, Wk = x * k, y * k, w * k
        md.ellipse((X - 0.36 * Wk, Y - 0.42 * Wk, X + 0.16 * Wk, Y + 0.10 * Wk), fill=255)
        md.ellipse((X + 0.02 * Wk, Y - 0.22 * Wk, X + 0.42 * Wk, Y + 0.18 * Wk), fill=255)
        md.rounded_rectangle((X - 0.5 * Wk, Y - 0.08 * Wk, X + 0.5 * Wk, Y + 0.24 * Wk), int(0.16 * Wk), fill=255)
        inner = mask.filter(ImageFilter.MinFilter(2 * st * k // 2 * 2 + 1))
        ring = ImageChops.subtract(mask, inner).resize((s, s), Image.LANCZOS)
        clear_mask = mask.resize((s, s), Image.LANCZOS)
        im.paste((0, 0, 0, 0), (0, 0), clear_mask)
        im.paste((255, 255, 255, 255), (0, 0), ring)

    if kind == "sun":
        sun(cx, cy, s * 0.2)
    elif kind == "partly":
        sun(cx - s * 0.16, cy - s * 0.16, s * 0.14)
        cloud(cx + s * 0.08, cy + s * 0.14, s * 0.62)
    elif kind in ("cloud", "rain", "storm", "snow"):
        cloud(cx, cy + (s * 0.04 if kind == "cloud" else -s * 0.06), s * 0.74)
        base = cy + s * 0.2
        if kind == "rain":
            for i in (-1, 0, 1):
                d.line((cx + i * s * 0.18, base, cx + i * s * 0.18 - s * 0.06, base + s * 0.16), fill=W_, width=st)
        elif kind == "snow":
            for i in (-1, 0, 1):
                d.ellipse((cx + i * s * 0.18 - st, base + s * 0.06 - st, cx + i * s * 0.18 + st, base + s * 0.06 + st), fill=W_)
        elif kind == "storm":
            d.line((cx + s * 0.04, base - s * 0.02, cx - s * 0.06, base + s * 0.12, cx + s * 0.06, base + s * 0.12, cx - s * 0.04, base + s * 0.26), fill=W_, width=st)
    elif kind == "moon":
        r = s * 0.3
        d.ellipse((cx - r, cy - r, cx + r, cy + r), fill=W_)
        d.ellipse((cx - r * 0.45, cy - r * 1.15, cx + r * 1.55, cy + r * 0.85), fill=clear)
    return im


def predimmed(src, dim, tint, out, quality=82):
    sc = D.Screen(tint)
    sc.photo(src, dim, tint)
    sc.img.save(out, "JPEG", quality=quality, optimize=True, progressive=True)


def stars(out):
    import random
    sc = D.Screen((5, 7, 15))
    rnd = random.Random(17)
    for _ in range(170):
        x, y, r = rnd.randint(0, 1920), rnd.randint(0, 1080), rnd.choice([1, 1, 1, 1.5, 2])
        sc.dot(x, y, r, (244, 241, 234, rnd.choice([60, 90, 130, 180])))
    sc.img.save(out, "JPEG", quality=85)


def arc(w, h, out, dash=(2, 14), width=3, alpha=110):
    k = 2
    im = Image.new("RGBA", (w * k, h * k), (0, 0, 0, 0))
    d = ImageDraw.Draw(im)
    pts = [(w * k * t / 200, h * k - 4 * k - (h * k - 8 * k) * 4 * (t / 200) * (1 - t / 200)) for t in range(201)]
    for i in range(0, 200, 4):
        d.line(pts[i] + pts[i + 1], fill=(255, 255, 255, alpha), width=width * k)
    im.resize((w, h), Image.LANCZOS).save(out)


def art(w, h, path, title_size, sub=True):
    sc = D.Screen()
    sc.img = sc.img.resize((w, h))
    sc.d = ImageDraw.Draw(sc.img, "RGBA")
    cx, cy = w / 2, h * 0.52
    r = h * 0.16
    sc.d.arc((cx - r * 2.2, cy - r * 1.2, cx + r * 2.2, cy + r * 3.2), 200, 340, fill=D.AMBER, width=max(3, int(h * 0.012)))
    sc.dot(cx, cy - r * 0.1, r * 0.45, D.AMBER)
    sc.text(cx, cy + r * 0.9, "Daybreak", title_size, 500, D.TEXT, "Outfit", anchor="ma")
    if sub:
        sc.text(cx, cy + r * 0.9 + title_size * 1.3, "The " + family["household"], int(title_size * 0.4), 500, D.TEXT_2, anchor="ma")
    sc.img.save(path)


def make_images():
    IMG.mkdir(exist_ok=True)
    for r in (10, 14, 18, 22, 28, 32):
        nine_patch(r).save(IMG / f"card{r}.9.png")
        nine_patch(r, ring=True).save(IMG / f"ring{r}.9.png")
    dot = Image.new("RGBA", (256, 256), (0, 0, 0, 0))
    ImageDraw.Draw(dot).ellipse((0, 0, 255, 255), fill=(255, 255, 255, 255))
    dot.resize((64, 64), Image.LANCZOS).save(IMG / "dot.png")
    ring = Image.new("RGBA", (1028, 1028), (0, 0, 0, 0))
    ImageDraw.Draw(ring).ellipse((2, 2, 1025, 1025), outline=(255, 255, 255, 255), width=4)
    ring.resize((514, 514), Image.LANCZOS).save(IMG / "ring_radar.png")
    for k in ("sun", "partly", "cloud", "rain", "storm", "snow", "moon"):
        icon(k).save(IMG / f"wx_{k}.png")
    for i in range(30):
        age = (i + 0.5) * D_SYN / 30
        illum = (1 - math.cos(2 * math.pi * age / D_SYN)) / 2
        D.moon_image(240, illum, age < D_SYN / 2).save(IMG / f"moon_{i:02d}.png")
    predimmed("callaway_pool.jpg", 0.55, D.INK_DEEP, IMG / "bg_ambient.jpg")
    predimmed("callaway_pavilion.jpg", 0.78, D.INK, IMG / "bg_briefing.jpg")
    predimmed("callaway_pool.jpg", 0.70, D.INK, IMG / "bg_season.jpg")
    stars(IMG / "bg_sky.jpg")
    base = ROOT / "daybreak" / "cache" / "radar" / "base.png"
    if not base.exists():
        import radar_map
        base.parent.mkdir(parents=True, exist_ok=True)
        try:
            radar_map.build_base(radar_map.bbox(), base.parent)
        except OSError as e:  # offline: a plain map keeps the build (and previews) working
            print(f"radar base map unavailable ({e}); using a plain background")
            Image.new("RGB", (1920, 1080), D.INK).save(base)
    Image.open(base).convert("RGB").save(IMG / "radar_base.jpg", "JPEG", quality=85, optimize=True)
    arc(1520, 190, IMG / "arc_ambient.png")
    arc(504, 56, IMG / "arc_card.png", width=3, alpha=150)
    art(336, 210, IMG / "icon_hd.png", 44, sub=False)
    art(540, 405, IMG / "icon_fhd.png", 70)
    art(1920, 1080, IMG / "splash_fhd.jpg", 140)


D_SYN = 29.530588853

def build_number():
    try:
        return int(subprocess.run(["git", "rev-list", "--count", "HEAD"], capture_output=True, text=True,
                                  cwd=ROOT, check=True).stdout.strip())
    except (OSError, subprocess.CalledProcessError, ValueError):
        return 0


def manifest_text():
    lines = (CH / "manifest").read_text().splitlines()
    return "\n".join(f"build_version={build_number()}" if l.startswith("build_version=") else l for l in lines) + "\n"


def bsc_check():
    check = subprocess.run(["npx", "-y", "brighterscript@0.65.27", "--rootDir", str(CH), "--createPackage", "false"],
                           capture_output=True, text=True, cwd=HERE)
    diag = [l for l in (check.stdout + check.stderr).splitlines() if " - error " in l or " - warning " in l or "Found " in l]
    print("\n".join(diag) or "bsc: no diagnostics")
    print("bsc exit:", check.returncode)
    return check.returncode


if __name__ == "__main__":
    write_config()
    if CHECK_ONLY:
        sys.exit(bsc_check())
    make_fonts()
    make_images()
    if ASSETS_ONLY:
        sys.exit(0)
    if bsc_check() != 0:
        sys.exit("BrighterScript reported errors; not packaging.")
    DIST.mkdir(exist_ok=True)
    out = DIST / "daybreak.zip"
    with zipfile.ZipFile(out, "w", zipfile.ZIP_DEFLATED) as z:
        z.writestr("manifest", manifest_text())
        for p in sorted(CH.rglob("*")):
            if p.is_file() and not p.name.startswith(".") and p.name != "manifest":
                z.write(p, p.relative_to(CH))
    print(f"packaged {out} ({out.stat().st_size // 1024} KB), build {build_number()}")
